import { strict as assert } from 'node:assert';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { ownsCommunityQuestion } from '../src/lib/communityOwnership';

const db = new PGlite();
await db.exec(`
 CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
 GRANT USAGE ON SCHEMA auth TO authenticated, anon;
 CREATE TABLE profiles(user_id uuid,full_name text,avatar_url text,preferred_city text,anonymous_handle text,email text);
 CREATE TABLE community_questions(id uuid, user_id uuid,title text,content text);
 CREATE TABLE community_answers(id uuid,question_id uuid,user_id uuid,content text,is_accepted boolean,is_verified_pro boolean,is_anonymous boolean,upvotes integer,downvotes integer,created_at timestamptz,updated_at timestamptz);
 CREATE TABLE community_expert_stats(user_id uuid,is_verified_professional boolean,professional_title text);
 ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
 ALTER TABLE community_answers ENABLE ROW LEVEL SECURITY;
 ALTER TABLE community_questions ENABLE ROW LEVEL SECURITY;
 GRANT SELECT ON profiles,community_answers TO authenticated;
 GRANT SELECT, UPDATE ON community_questions TO authenticated;
 CREATE POLICY question_read ON community_questions FOR SELECT TO authenticated USING(auth.uid() IS NOT NULL);
 CREATE POLICY question_edit ON community_questions FOR UPDATE TO authenticated USING(auth.uid()=user_id) WITH CHECK(auth.uid()=user_id);
 INSERT INTO profiles VALUES ('00000000-0000-0000-0000-000000000001','Aris Koutsoukis',NULL,NULL,'Anonymous #1','private@example.test'),('00000000-0000-0000-0000-000000000002','Klodia Koutsouki',NULL,NULL,'Anonymous #2','private2@example.test');
 INSERT INTO community_questions VALUES ('00000000-0000-0000-0000-000000000010','00000000-0000-0000-0000-000000000001','Row diet','Original details');
 INSERT INTO community_answers VALUES ('00000000-0000-0000-0000-000000000011','00000000-0000-0000-0000-000000000010','00000000-0000-0000-0000-000000000002','Named reply',false,false,false,0,0,now(),now()),('00000000-0000-0000-0000-000000000012','00000000-0000-0000-0000-000000000010','00000000-0000-0000-0000-000000000002','Anonymous reply',false,true,true,0,0,now(),now());
`);
await db.exec(readFileSync(new URL('../drizzle/migrations/0011_community_safe_display_access.sql',import.meta.url),'utf8'));
await db.exec(`SET ROLE authenticated; SET test.uid='00000000-0000-0000-0000-000000000003';`);
assert.equal((await db.query('SELECT * FROM profiles')).rows.length,0,'Private profiles stay restricted');
assert.equal((await db.query('SELECT * FROM community_answers')).rows.length,0,'Raw answers stay restricted');
const profiles = (await db.query<{full_name:string}>('SELECT * FROM profiles_public')).rows;
assert.equal(profiles[0].full_name,'Aris Koutsoukis','Another member sees the named question author');
assert.equal('email' in profiles[0],false,'Display view never includes email');
const replies = (await db.query<{content:string;author_name:string;author_avatar_url:string|null;is_verified_pro:boolean}>('SELECT * FROM community_answers_public ORDER BY id')).rows;
assert.equal(replies.length,2,'Unrelated member can read replies');
assert.equal(replies[0].author_name,'Klodia Koutsouki','Named reply retains the author name');
assert.equal(replies[1].author_name,'Anonymous #2','Anonymous reply masks the real name');
assert.equal(replies[1].author_avatar_url,null);
assert.equal(replies[1].is_verified_pro,false);
assert.equal('user_id' in replies[1],false,'Anonymous reply cannot reveal owner ID');
assert.equal((await db.query(`UPDATE community_questions SET title='Wrong owner' RETURNING id`)).rows.length,0,'Non-author cannot edit');
await db.exec(`SET test.uid='00000000-0000-0000-0000-000000000001';`);
assert.equal((await db.query(`UPDATE community_questions SET title='Raw diet' RETURNING title`)).rows.length,1,'Original author can correct the question');
assert.equal((await db.query<{title:string}>('SELECT title FROM community_questions')).rows[0].title,'Raw diet');
await db.exec(`SET test.uid='';`);
assert.equal((await db.query('SELECT * FROM profiles_public')).rows.length,0,'Signed-out viewers see no display profiles');
assert.equal((await db.query('SELECT * FROM community_answers_public')).rows.length,0,'Signed-out viewers see no replies');
assert.equal(ownsCommunityQuestion('aris','aris'),true);
assert.equal(ownsCommunityQuestion('aris','koboulinis3'),false);
assert.equal(ownsCommunityQuestion(null,undefined),false);
await db.close();
console.log('Community display privacy, reply visibility and question ownership tests passed');